function Clear-Screen {
    if ($Host.Name -eq 'ConsoleHost') {
        Clear-Host
    }
}

function Write-Color {
    param([string]$Text, [string]$Color = 'White')
    Write-Host $Text -ForegroundColor $Color
}

function banner($Title) {
    Clear-Screen
    Write-Color "`n  $Title" -Color Cyan
    Write-Color "  $TOTAL_STAGES stages`n" -Color DarkGray
    Write-Color "  You drive the browser; this wizard tells you exactly what to do and" -Color DarkGray
    Write-Color "  captures the values you copy back. Stop any time with Ctrl-C and re-run" -Color DarkGray
    Write-Color "  later, since it remembers values already saved.`n" -Color DarkGray
    pause "Ready to start?"
}

function stage($Name) {
    Clear-Screen
    $script:STAGE_INDEX++
    Write-Color "`n▸ Stage $STAGE_INDEX/$TOTAL_STAGES · $Name" -Color Cyan
}

function say($Text) { Write-Host "  $Text" }
function step($Text) { Write-Color "  • $Text" -Color Blue }
function note($Text) { Write-Color "  $Text" -Color DarkGray }
function warn($Text) { Write-Color "  ⚠ $Text" -Color Yellow }

function open_url($Url) {
    Write-Color "  ↗ opening $Url" -Color Green
    try {
        Start-Process $Url -ErrorAction Stop | Out-Null
    }
    catch {
        warn "couldn't open browser automatically. Please visit: $Url"
    }
}

function pause($Message = "Press Enter to continue") {
    Write-Host "  $Message" -NoNewline -ForegroundColor DarkGray
    Read-Host
}

function confirm($Question) {
    $reply = Read-Host "  ? $Question [y/N]"
    return $reply -match '^[Yy]'
}

# Reads existing value from .env file
function _existing($Key) {
    if (!(Test-Path $ENV_FILE)) { return $null }
    $line = Get-Content $ENV_FILE | Where-Object { $_ -match "^$Key=" } | Select-Object -Last 1
    if (!$line) { return $null }
    
    $value = $line -replace "^$Key=", ""
    $value = $value.Trim('"', "'")
    return $value
}

function ask($Key, $Prompt) {
    $current = _existing $Key
    $promptText = "  $Prompt"
    if ($current) {
        $promptText += " [Enter keeps current]"
    }
    
    $input = Read-Host $promptText
    
    if ([string]::IsNullOrWhiteSpace($input) -and $current) {
        $input = $current
    }
    
    Set-Variable -Name $Key -Value $input -Scope Script
    return $input
}

function ask_secret($Key, $Prompt) {
    $current = _existing $Key
    if ($current) {
        Write-Host "  $Prompt [Enter keeps current]" -ForegroundColor White -NoNewline
    } else {
        Write-Host "  $Prompt" -ForegroundColor White -NoNewline
    }
    
    $input = Read-Host -AsSecureString
    
    if ($input.Length -eq 0 -and $current) {
        $value = $current
    } else {
        $value = [Runtime.InteropServices.Marshal]::PtrToStringAuto(
            [Runtime.InteropServices.Marshal]::SecureStringToBSTR($input))
    }
    
    Set-Variable -Name $Key -Value $value -Scope Script
    return $value
}

function write_env($Key, $Value) {
    if (!(Test-Path $ENV_FILE)) {
        $null = New-Item $ENV_FILE -ItemType File -Force
    }
    
    $content = Get-Content $ENV_FILE -ErrorAction SilentlyContinue | Where-Object { $_ -notmatch "^$Key=" }
    
    # Escape single quotes for PowerShell-style .env
    $escaped = $Value -replace "'", "''"
    $content += "$Key='$escaped'"
    
    $content | Set-Content $ENV_FILE
    Set-Variable -Name $Key -Value $Value -Scope Script
    
    $script:WRITTEN_ENV += $Key
    Write-Color "  ✓ wrote $Key → $ENV_FILE" -Color Green
}

function set_secret($Name, $Value) {
    Write-Color "  ⚠ GitHub CLI secret setting not yet implemented in PowerShell version" -Color Yellow
    $script:SKIPPED += "GitHub secret $Name (set manually)"
    warn "skipped GitHub secret $Name"
}

function set_var($Name, $Value) {
    Write-Color "  ⚠ GitHub CLI variable setting not yet implemented in PowerShell version" -Color Yellow
    $script:SKIPPED += "GitHub variable $Name"
    warn "skipped GitHub variable $Name"
}

function finish {
    Clear-Screen
    Write-Color "`n  ✓ Setup complete" -Color Green
    
    if ($WRITTEN_ENV.Count -gt 0) {
        note "wrote $($WRITTEN_ENV.Count) value(s) to $ENV_FILE: $($WRITTEN_ENV -join ', ')"
    }
    if ($WRITTEN_SECRET.Count -gt 0) {
        note "set $($WRITTEN_SECRET.Count) GitHub secret(s): $($WRITTEN_SECRET -join ', ')"
    }
    if ($SKIPPED.Count -gt 0) {
        Write-Host "`n" 
        warn "still to do by hand:"
        foreach ($item in $SKIPPED) {
            note "  - $item"
        }
    }
    Write-Host ""
}

